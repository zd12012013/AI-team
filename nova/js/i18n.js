/** Перевод фразы интерфейса. В фразе можно писать {имя} — подставится из vars. */
function tr(ru, vars = {}) {
  const s = isKz() && KZ_UI[ru] !== undefined ? KZ_UI[ru] : ru;
  return s.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? "");
}
/** Русская форма множественного числа; в казахском существительное после числа не меняется. */
function trn(n, one, few, many) {
  if (isKz()) return tr(one);
  const m10 = n % 10, m100 = n % 100;
  return m10 === 1 && m100 !== 11 ? one : m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14) ? few : many;
}
